/** Trust boundary: local canonical, local M30 and local M31. No POST, storage or AI.
 * Cross-check fingerprints with a conservative Python-json-compatible encoder.
 * Divergent numeric lexical conventions FAIL CLOSED instead of approximating.
 */
const isObject=v=>v!==null&&typeof v==="object"&&!Array.isArray(v);
export const SECTION_IDS=[
"S01_SYNTHESIS","S02_DATA_METHOD","S03_NUMERIC_ONTOLOGY","S04_STRUCTURE",
"S05_RELATIONAL","S06_DIFFERENTIAL","S07_TEMPORAL","S08_ROBUSTNESS",
"S09_DOCTRINE","S10_FINAL_SYNTHESIS","S11_SOURCES_APPENDICES",
"S12_PHASE_DYNAMICS"];
function pythonCompatibleJson(value) {
  if(value===null||typeof value==="boolean"||typeof value==="string")return JSON.stringify(value);
  if(typeof value==="number"){
    if(!Number.isFinite(value))throw Error("Nonfinite value");
    // Avoid false SHA certification on numbers whose original lexical
    // representation is unrecoverable from parsed JSON.
    if(Number.isInteger(value))throw Error("Ambiguous Python integer/float lexical form");
    return JSON.stringify(value);
  }
  if(Array.isArray(value))return "["+value.map(pythonCompatibleJson).join(",")+"]";
  if(!isObject(value))throw Error("Unsupported value");
  return "{"+Object.keys(value).sort().map(key=>JSON.stringify(key)+":"+pythonCompatibleJson(value[key])).join(",")+"}";
}
export async function digestCanonicalConservative(canonical) {
  try{
    const normalized=pythonCompatibleJson(canonical);
    const bytes=new TextEncoder().encode(normalized);
    const hash=await crypto.subtle.digest("SHA-256",bytes);
    return {ok:true,hash:[...new Uint8Array(hash)].map(x=>x.toString(16).padStart(2,"0")).join("")};
  }catch{
    return {ok:false,hash:null,reason:"La representación numérica no permite verificar exactamente la huella Python; usar comprobación local oficial M30."};
  }
}
export async function assessReportTriplet(canonical,gate,model,{validate,digest=digestCanonicalConservative}={}) {
  const fail=reason=>({ok:false,state:"BLOCKED",reason,sections:[]});
  if(typeof validate!=="function")return fail("Validador offline integral ausente");
  const check=[
    ["canonical-analysis.schema.json",canonical],
    ["report-gate-output.schema.json",gate],
    ["report-document-model.schema.json",model]
  ];
  for(const [schemaName,obj] of check){
    const result=validate(obj,schemaName);
    if(result?.ok!==true||result?.kind!=="JSON_SCHEMA_DRAFT_2020_12")return fail("Invalidez del esquema "+schemaName);
  }
  if(gate?.state==="BLOCKED"||gate?.reportable!==true)return fail("M30 bloquea la reportabilidad");
  if(!["READY","PARTIAL"].includes(gate?.state)||model?.report_state!==gate.state)
    return fail("Estados M30/M31 incompatibles");
  if(gate?.canonical_values_mutated!==false||
    model?.canonical_values_mutated!==false||
    model?.canonical_values_embedded!==false||
    model?.canonical_fingerprint_verified!==true||
    model?.prose_generated!==false)return fail("Invariantes de integridad no satisfechos");
  const fp=gate.canonical_fingerprint;
  if(!/^[a-f0-9]{64}$/.test(fp)||model.canonical_fingerprint!==fp)return fail("Huellas M30/M31 divergentes");
  const calculated=await digest(canonical);
  if(!calculated?.ok||calculated.hash!==fp)return fail("Huella canónica local sin verificación independiente");
  const sections=Array.isArray(model.sections)?model.sections:[];
  if(sections.length!==SECTION_IDS.length||
    sections.some((s,i)=>s?.section_id!==SECTION_IDS[i]||s?.order!==i+1))
    return fail("Orden o identidad de las 12 secciones inválidos");
  return {
    ok:true,state:gate.state,reason:null,fingerprint:fp,
    sections:sections.map(s=>({
      id:s.section_id,title:s.title,state:s.section_state,
      requiredMissing:Array.isArray(s.missing_required_paths)?s.missing_required_paths.slice():[],
      optionalMissing:Array.isArray(s.missing_optional_paths)?s.missing_optional_paths.slice():[],
      classes:Array.isArray(s.epistemic_classes_allowed)?s.epistemic_classes_allowed.slice():[]
    })),
    degradationReasons:Array.isArray(gate.degradation_reasons)?gate.degradation_reasons.slice():[],
    // A validated M31 is a declarative model, NOT narrative generated by ALMAS.
    narrativeGenerated:false
  };
}
const escapeHtml=value=>String(value).replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
export function createLocalReportHtml(verified) {
  if(verified?.ok!==true||!["READY","PARTIAL"].includes(verified.state)||
    !/^[a-f0-9]{64}$/.test(verified.fingerprint||""))throw Error("Report cannot be exported without validation");
  const items=verified.sections.map(s=>'<section><h2>'+escapeHtml(s.id)+" — "+escapeHtml(s.title)+
    '</h2><p>Estado: '+escapeHtml(s.state)+'</p><p>Faltan rutas obligatorias: '+
    escapeHtml(s.requiredMissing.join(", ")||"ninguna")+'</p><p>Clases permitidas: '+
    escapeHtml(s.classes.join(", "))+'</p></section>').join("");
  return '<!doctype html><html lang="es"><head><meta charset="utf-8"><title>ALMAS M31 — '+escapeHtml(verified.state)+'</title><style>body{font:16px system-ui;max-width:850px;margin:auto;padding:2em;line-height:1.5}section{break-inside:avoid;border-top:1px solid #bbb;padding-top:1em}@media print{button{display:none}}</style></head><body><h1>ALMAS · Modelo documental M31</h1><p>Estado '+escapeHtml(verified.state)+' · huella '+escapeHtml(verified.fingerprint)+'</p><p>Documento declarativo local. No se ha generado narrativa interpretativa y no certifica hipótesis metafísicas.</p>'+items+'</body></html>';
}
